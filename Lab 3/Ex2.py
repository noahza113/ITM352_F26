'''

Create a function-call it midpooint that takes two numbers as input and returns the midpoint of those two numbers. The midpoint is calculated by adding the two numbers together and dividing by 2.
'''

def midpoint(num1, num2):
    return ((num1 + num2)/2)

print (midpoint(10, 20)) #Output: 15.0
print (midpoint(0, 10)) #Output: 5.0